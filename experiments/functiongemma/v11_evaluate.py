"""Score a V11 adapter on the held-out split, and sweep checkpoints.

Read the numbers this produces alongside `v11_stress_probe`, never alone. The held-out split was
generated by the same process as the training split and carries the same seven measured shortcuts,
so a high score here is compatible with a model that never reads the goal. What this module is
genuinely good for is the things the shortcuts cannot fake:

* **Contract validity.** Does every emission parse, and is every step one the on-device helper
  could actually run? A model that emits `next_step(kind="goto")` or two selectors at once is
  useless regardless of its accuracy, because `FlowFeature.runStep` will reject it.
* **Selector grounding.** Does the emitted selector name a node that is actually on the screen?
  Invented selectors are the failure mode that turns into a device timeout rather than a wrong tap.
* **False refusal.** Handing off when the target is right there is how an autopilot becomes useless
  rather than dangerous, and the corpus cannot make that look good by accident.
* **Per-family breakdown.** Selection should be on the worst family, never the mean. V10's first
  run sat at 0.001 validation loss while refusing 0 of 38 handoff cells.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from .v11_contract import ContractError, validate_step
from .v11_stress_probe import parse


def _oracle(row: dict[str, Any]) -> dict[str, Any]:
    """The row's own label, parsed back into the comparable shape."""

    answer = parse(row["messages"][2]["content"])
    if answer is None:
        raise ValueError(f"row {row['id']} has an unparseable label")
    return answer


def _selector_of(answer: dict[str, Any]) -> tuple[str, str] | None:
    for field, key in (("resource_id", "rid"), ("label", "text"), ("content_desc", "desc")):
        if answer.get(field):
            return key, str(answer[field])
    return None


def evaluate(
    model_path: str,
    adapter_path: str,
    data: Path,
    *,
    limit: int | None = None,
    max_tokens: int = 48,
) -> dict[str, Any]:
    from mlx_lm import generate, load  # noqa: PLC0415

    loaded = load(model_path, adapter_path=adapter_path)
    model, tokenizer = loaded[0], loaded[1]

    rows = [json.loads(line) for line in data.open(encoding="utf-8")]
    if limit:
        # Stride rather than truncate: the file is written trajectory by trajectory, so the first
        # N rows are the first few journeys and would not cover the family mix at all.
        stride = max(1, len(rows) // limit)
        rows = rows[::stride][:limit]

    per_family: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    unparseable = 0
    invalid_step = 0
    ungrounded = 0
    call_confusion: Counter[str] = Counter()
    refusal = [0, 0]  # correct handoffs / rows whose oracle is a handoff
    false_refusal = [0, 0]  # handoffs emitted / rows whose oracle is an action
    correct = 0

    for row in rows:
        oracle = _oracle(row)
        context = json.loads(row["messages"][1]["content"])
        prompt = tokenizer.apply_chat_template(
            row["messages"][:2], tools=row["tools"], tokenize=False, add_generation_prompt=True
        )
        raw = generate(model, tokenizer, prompt=prompt, max_tokens=max_tokens, verbose=False)
        answer = parse(raw)
        family = row["metadata"]["family"]

        if answer is None:
            unparseable += 1
            per_family[family][1] += 1
            call_confusion[f"{oracle['call']}->unparseable"] += 1
            if oracle["call"] == "handoff":
                refusal[1] += 1
            else:
                false_refusal[1] += 1
            continue

        if answer["call"] == "next_step":
            step = {k: v for k, v in answer.items() if k != "call"}
            try:
                validate_step(step)
            except ContractError:
                invalid_step += 1
            selector = _selector_of(answer)
            if selector is not None:
                key, value = selector
                if not any(str(node.get(key)) == value for node in context["screen"]["nodes"]):
                    ungrounded += 1

        ok = all(str(answer.get(k)) == str(v) for k, v in oracle.items())
        correct += int(ok)
        per_family[family][0] += int(ok)
        per_family[family][1] += 1
        if not ok:
            call_confusion[f"{oracle['call']}->{answer['call']}"] += 1
        if oracle["call"] == "handoff":
            refusal[1] += 1
            refusal[0] += int(
                answer["call"] == "handoff" and answer.get("reason") == oracle.get("reason")
            )
        else:
            false_refusal[1] += 1
            false_refusal[0] += int(answer["call"] == "handoff")

    families = {
        name: {"accuracy": round(hit / total, 3), "n": total}
        for name, (hit, total) in sorted(per_family.items())
    }
    worst = min(families.items(), key=lambda item: item[1]["accuracy"]) if families else None
    return {
        "adapter": adapter_path,
        "rows": len(rows),
        "accuracy": round(correct / len(rows), 4) if rows else 0.0,
        "worst_family": {"name": worst[0], **worst[1]} if worst else None,
        "contract": {
            "unparseable": unparseable,
            "invalid_step": invalid_step,
            "ungrounded_selector": ungrounded,
        },
        "refusal": {
            "recall": round(refusal[0] / refusal[1], 3) if refusal[1] else None,
            "n": refusal[1],
        },
        "false_refusal": {
            "rate": round(false_refusal[0] / false_refusal[1], 3) if false_refusal[1] else None,
            "n": false_refusal[1],
        },
        "families": families,
        "confusions": dict(call_confusion.most_common(10)),
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True)
    parser.add_argument("--adapter", required=True, help="adapter directory, or a checkpoint file")
    parser.add_argument("--data", type=Path, default=Path("runs/functiongemma/data-v11/test.jsonl"))
    parser.add_argument("--limit", type=int, default=400)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)

    report = evaluate(args.model, args.adapter, args.data, limit=args.limit)
    print(json.dumps(report, indent=2, sort_keys=True))
    if args.out:
        args.out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", "utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
