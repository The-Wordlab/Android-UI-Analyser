"""Stress probe: does a V11 adapter read the goal, or the shortcuts?

Seven rules were measured in the V11 corpus that predict the correct answer at precision 1.000
without reading the goal at all — a scrollable node means `scroll-to`, an `assert-visible` at the end
of the history means `done`, a goal beginning "Remove" means `needs_authorization`, and so on. A
held-out score cannot detect any of them, because the held-out split was generated by the same
process and carries the same regularities. It will look excellent and mean nothing.

This module builds the measurement that can tell the difference. For each measured shortcut it
constructs states where **the shortcut and the correct answer disagree**, and where the correct
answer is unambiguous under the contract in `v11_contract`. A model that learned the task answers
these; a model that learned the shortcut fails them in a specific, predictable direction, which is
recorded as ``shortcut_answer`` so the failure mode is visible rather than inferred.

Every probe reports both numbers so the gap is the headline:

* ``control`` — unmutated states of the same family, which the shortcut also gets right.
* ``stressed`` — the same states with the shortcut broken.

A large control-minus-stressed gap is the shortcut being used. Equal scores mean the capability is
real.

**Honest limitation.** This probe was authored by the same process that authored the generator, and
this experiment's own history says exactly what that is worth: the V9 acceptance probe scored 6/6 on
refusing an absent target and an independently authored audit then measured 0/144. What protects
this one is narrower than independence: each mutation was derived from a *measured* correlation
rather than from reading the generator, and each oracle is forced by the contract rather than chosen.
That is weaker than an independent author and should not be mistaken for one. Treat a good result
here as "the shortcuts specifically are not being used", never as "the model is good".
"""

from __future__ import annotations

import argparse
import json
import re
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from .v11_contract import tools
from .v11_curriculum import DRIVER_POLICY

#: Opaque resource ids, deliberately carrying no words from any goal. The corpus emits `navTab`
#: plus a camel-cased section name for every single rid answer, in all three splits, so a rid there
#: is just the label in another font. These are what a real Compose screen frequently looks like.
OPAQUE_RIDS = ("btn_9c2", "fab_main", "row_017", "v_1a4f", "cell_x2", "ctl_88")

CALL = re.compile(r"\s*<\|tool_call_start\|>\[(\w+)\((.*?)\)\]<\|tool_call_end\|>\s*", re.DOTALL)


def parse(output: str) -> dict[str, Any] | None:
    """Parse one emitted call into ``{"call": name, ...arguments}``, or None if malformed."""

    match = CALL.fullmatch(output)
    if match is None:
        return None
    name, body = match.group(1), match.group(2)
    parsed: dict[str, Any] = {"call": name}
    for piece in re.finditer(r'(\w+)="([^"]*)"|(\w+)=(True|False)', body):
        if piece.group(1) is not None:
            parsed[piece.group(1)] = piece.group(2)
        else:
            parsed[piece.group(3)] = piece.group(4) == "True"
    return parsed


# --------------------------------------------------------------------------- probe construction


def _node(rid=None, text=None, desc=None, clickable=True, scrollable=False) -> dict[str, Any]:
    node: dict[str, Any] = {}
    if rid:
        node["rid"] = rid
    if text:
        node["text"] = text
    if desc:
        node["desc"] = desc
    if clickable:
        node["clickable"] = True
    if scrollable:
        node["scrollable"] = True
    return node


def _case(
    probe: str,
    goal: str,
    nodes: list[dict[str, Any]],
    oracle: dict[str, Any],
    shortcut_answer: str,
    *,
    history: list[str] | None = None,
    ime: bool = False,
    stressed: bool = True,
    accept: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    screen: dict[str, Any] = {"package": "example.probe.app", "nodes": nodes}
    if ime:
        screen["ime"] = True
    context: dict[str, Any] = {
        "goal": goal,
        "step": len(history or []),
        "budget": 10,
        "screen": screen,
    }
    if history:
        context["history"] = history
    return {
        "probe": probe,
        "stressed": stressed,
        "context": context,
        "oracle": oracle,
        "accept": accept or [oracle],
        "shortcut_answer": shortcut_answer,
    }


#: Sections used only by this probe, drawn from none of the generator's split pools, so no case
#: here can be answered from a memorised destination name.
S = ("Wharf", "Bastion", "Rookery", "Quarry", "Foundry", "Weir", "Kiln", "Byre")


def cases() -> list[dict[str, Any]]:
    """Every probe case, control and stressed, paired by construction."""

    out: list[dict[str, Any]] = []

    # P1 — scrollable decoy. The corpus contains zero refusal states with a scrollable node, and a
    # scrollable node predicts `scroll-to` perfectly. Real screens almost always have one.
    absent, present = S[0], S[1:4]
    base = [_node(text=name) for name in present]
    out.append(
        _case(
            "scroll_decoy",
            f"Open the {absent} section and prove its page",
            base + [_node(text="Version", clickable=False)],
            {"call": "handoff", "reason": "target_absent"},
            "next_step scroll-to",
            stressed=False,
        )
    )
    out.append(
        _case(
            "scroll_decoy",
            f"Open the {absent} section and prove its page",
            base + [_node(rid="listContainer", clickable=False, scrollable=True)],
            {"call": "handoff", "reason": "target_absent"},
            "next_step scroll-to",
        )
    )

    # P2 — premature done. "Last history line is an assert-visible" predicts `done` perfectly. Here
    # a waypoint was asserted but the destination is not reached and its control is on screen.
    way, dest = S[4], S[5]
    out.append(
        _case(
            "premature_done",
            f"Open {way}, then land on {dest}",
            [_node(text=dest), _node(text=S[6])],
            {"call": "next_step", "kind": "tap", "label": dest},
            "done",
            history=[f"tap text={way}"],
            stressed=False,
        )
    )
    out.append(
        _case(
            "premature_done",
            f"Open {way}, then land on {dest}",
            [_node(text=dest), _node(text=S[6])],
            {"call": "next_step", "kind": "tap", "label": dest},
            "done",
            history=[f"tap text={way}", f"assert-visible {way}"],
        )
    )

    # P3 — destructive verb, navigable target. A goal opening Remove/Delete/Erase/Discard predicts
    # `needs_authorization` perfectly. Here nothing destructive is on screen and the named section
    # is right there, so navigating to it is the only step that advances the goal.
    target = S[2]
    safe = [_node(text=target), _node(text=S[3]), _node(text="Storage used", clickable=False)]
    out.append(
        _case(
            "destructive_verb_navigable",
            f"Open the {target} section and prove its page",
            safe,
            {"call": "next_step", "kind": "tap", "label": target},
            "handoff needs_authorization",
            stressed=False,
        )
    )
    out.append(
        _case(
            "destructive_verb_navigable",
            f"Remove the {target} entry",
            safe,
            {"call": "next_step", "kind": "tap", "label": target},
            "handoff needs_authorization",
        )
    )

    # P4 — varied stall. `no_progress` is a literal four-line history in the corpus.
    gone = S[7]
    here = [_node(text=S[0]), _node(text=S[1])]
    canned = [f"tap text={S[0]}", "key back", f"tap text={S[0]}", "key back"]
    varied = [
        f"tap text={S[1]}",
        "key back",
        f"tap desc={S[0]}",
        "wait-stable",
        "key back",
        f"tap text={S[1]}",
        "key back",
    ]
    out.append(
        _case(
            "varied_stall",
            f"Open the {gone} section and prove its page",
            here,
            {"call": "handoff", "reason": "no_progress"},
            "next_step tap",
            history=canned,
            stressed=False,
            accept=[
                {"call": "handoff", "reason": "no_progress"},
                {"call": "handoff", "reason": "target_absent"},
            ],
        )
    )
    out.append(
        _case(
            "varied_stall",
            f"Open the {gone} section and prove its page",
            here,
            {"call": "handoff", "reason": "no_progress"},
            "next_step tap",
            history=varied,
            accept=[
                {"call": "handoff", "reason": "no_progress"},
                {"call": "handoff", "reason": "target_absent"},
            ],
        )
    )

    # P5 — host lane naming an on-screen section. "No capitalised token after the first" predicts
    # `needs_host_lane` at precision 1.000; every device goal in the corpus names a capitalised
    # destination and no host-lane goal does.
    section = S[3]
    screen = [_node(text=section), _node(text=S[4])]
    out.append(
        _case(
            "host_lane_named_section",
            "Capture the network calls this screen makes",
            screen,
            {"call": "handoff", "reason": "needs_host_lane"},
            "next_step tap",
            stressed=False,
        )
    )
    out.append(
        _case(
            "host_lane_named_section",
            f"Capture the network calls the {section} tab makes",
            screen,
            {"call": "handoff", "reason": "needs_host_lane"},
            "next_step tap",
        )
    )

    # P6 — opaque resource id. All 8,178 rid answers in the corpus begin `navTab` plus the section
    # name, in every split, so a rid never has to be read as an identifier. Here the target is
    # identified by its text and carries an opaque rid; either selector is contract-valid.
    dest2 = S[5]
    out.append(
        _case(
            "opaque_rid",
            f"Open the {dest2} section and prove its page",
            [_node(rid=f"navTab{dest2}", text=dest2), _node(text=S[6]), _node(text=S[7])],
            {"call": "next_step", "kind": "tap", "resource_id": f"navTab{dest2}"},
            "next_step tap on a navTab-prefixed rid",
            stressed=False,
            accept=[
                {"call": "next_step", "kind": "tap", "resource_id": f"navTab{dest2}"},
                {"call": "next_step", "kind": "tap", "label": dest2},
            ],
        )
    )
    out.append(
        _case(
            "opaque_rid",
            f"Open the {dest2} section and prove its page",
            [
                _node(rid=OPAQUE_RIDS[0], text=dest2),
                _node(rid=OPAQUE_RIDS[1], text=S[6]),
                _node(rid=OPAQUE_RIDS[2], text=S[7]),
            ],
            {"call": "next_step", "kind": "tap", "resource_id": OPAQUE_RIDS[0]},
            "next_step tap on the wrong node",
            accept=[
                {"call": "next_step", "kind": "tap", "resource_id": OPAQUE_RIDS[0]},
                {"call": "next_step", "kind": "tap", "label": dest2},
            ],
        )
    )

    # P8 — the reverse router. A device goal wearing host-lane clothes: lowercase destination, plus
    # the exact length filler the host-lane generator uses. The trained model answered
    # `handoff(needs_host_lane)` on precisely this shape, which is what withdrew the accepted
    # residual in `v11_shortcut_gate.ACCEPTED_RESIDUALS`. The target is on screen; the only correct
    # answer is to tap it.
    plain = S[1]
    out.append(
        _case(
            "reverse_router",
            f"Open the {plain} section and prove its page",
            [_node(text=plain), _node(text=S[2]), _node(text=S[3])],
            {"call": "next_step", "kind": "tap", "label": plain},
            "handoff needs_host_lane",
            stressed=False,
        )
    )
    out.append(
        _case(
            "reverse_router",
            f"Could you open {plain.lower()} for me — this is the whole task",
            [_node(text=plain), _node(text=S[2]), _node(text=S[3])],
            {"call": "next_step", "kind": "tap", "label": plain},
            "handoff needs_host_lane",
        )
    )

    # P7 — keyboard up, but typing is the goal. `ime: true` predicts `hide-keyboard` perfectly,
    # while on a real device the keyboard is up precisely because a field was just focused.
    out.append(
        _case(
            "ime_but_type",
            f"Search for {S[0]} and open the first result",
            [_node(rid="searchField")],
            {"call": "next_step", "kind": "input", "resource_id": "searchField", "text": S[0]},
            "next_step hide-keyboard",
            stressed=False,
        )
    )
    out.append(
        _case(
            "ime_but_type",
            f"Search for {S[0]} and open the first result",
            [_node(rid="searchField")],
            {"call": "next_step", "kind": "input", "resource_id": "searchField", "text": S[0]},
            "next_step hide-keyboard",
            ime=True,
        )
    )
    return out


# --------------------------------------------------------------------------- scoring


def matches(answer: dict[str, Any] | None, accept: Sequence[dict[str, Any]]) -> bool:
    """An answer counts only if every field of some accepted oracle agrees exactly."""

    if answer is None:
        return False
    for option in accept:
        if all(str(answer.get(key)) == str(value) for key, value in option.items()):
            return True
    return False


def run(model_path: str, adapter_path: str, *, permutations: int = 4) -> dict[str, Any]:
    """Score every probe case under several node orderings."""

    import random  # noqa: PLC0415

    from mlx_lm import generate, load  # noqa: PLC0415

    loaded = load(model_path, adapter_path=adapter_path)
    model, tokenizer = loaded[0], loaded[1]
    tool_defs = tools()

    results: dict[str, dict[str, Any]] = {}
    details: list[dict[str, Any]] = []
    for case in cases():
        bucket = results.setdefault(
            case["probe"],
            {"control": [0, 0], "stressed": [0, 0], "shortcut_answer": case["shortcut_answer"]},
        )
        lane = "stressed" if case["stressed"] else "control"
        for permutation in range(permutations):
            context = json.loads(json.dumps(case["context"]))
            rnd = random.Random(f"{case['probe']}:{lane}:{permutation}")
            rnd.shuffle(context["screen"]["nodes"])
            messages = [
                {"role": "system", "content": DRIVER_POLICY},
                {
                    "role": "user",
                    "content": json.dumps(
                        context, ensure_ascii=False, separators=(",", ":"), sort_keys=True
                    ),
                },
            ]
            prompt = tokenizer.apply_chat_template(
                messages, tools=tool_defs, tokenize=False, add_generation_prompt=True
            )
            raw = generate(model, tokenizer, prompt=prompt, max_tokens=48, verbose=False)
            ok = matches(parse(raw), case["accept"])
            bucket[lane][0] += int(ok)
            bucket[lane][1] += 1
            details.append(
                {
                    "probe": case["probe"],
                    "lane": lane,
                    "permutation": permutation,
                    "ok": ok,
                    "emitted": raw.strip(),
                }
            )

    summary = {}
    for probe, bucket in results.items():
        control_ok, control_n = bucket["control"]
        stressed_ok, stressed_n = bucket["stressed"]
        control = control_ok / control_n if control_n else 0.0
        stressed = stressed_ok / stressed_n if stressed_n else 0.0
        summary[probe] = {
            "control": f"{control_ok}/{control_n}",
            "stressed": f"{stressed_ok}/{stressed_n}",
            "gap": round(control - stressed, 3),
            "shortcut_answer": bucket["shortcut_answer"],
        }
    total_control = sum(b["control"][0] for b in results.values())
    total_control_n = sum(b["control"][1] for b in results.values())
    total_stressed = sum(b["stressed"][0] for b in results.values())
    total_stressed_n = sum(b["stressed"][1] for b in results.values())
    return {
        "adapter": adapter_path,
        "permutations": permutations,
        "probes": summary,
        "overall": {
            "control": f"{total_control}/{total_control_n}",
            "stressed": f"{total_stressed}/{total_stressed_n}",
            "gap": round(total_control / total_control_n - total_stressed / total_stressed_n, 3)
            if total_control_n and total_stressed_n
            else None,
        },
        "details": details,
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", required=True)
    parser.add_argument("--adapter", required=True)
    parser.add_argument("--permutations", type=int, default=4)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)

    report = run(args.model, args.adapter, permutations=args.permutations)
    printable = {key: value for key, value in report.items() if key != "details"}
    print(json.dumps(printable, indent=2, sort_keys=True))
    if args.out:
        args.out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", "utf-8")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
